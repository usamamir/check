export function getExercise(id: string) {
  return exercises.find((e) => e.id === id)
}

export function filterExercises(opts: {
  equipment: Equipment[]
  muscles: Muscle[]
  query?: string
}) {
  const eq = new Set(opts.equipment)
  const ms = new Set(opts.muscles)
  const q = (opts.query || '').trim().toLowerCase()
  return exercises.filter((ex) => {
    const equipOk = !eq.size || ex.equipment.some((e) => eq.has(e))
    const muscleOk = !ms.size || ex.muscles.some((m) => ms.has(m))
    const textOk = !q || ex.name.toLowerCase().includes(q)
    return equipOk && muscleOk && textOk
  })
}

export function exercisesForMuscle(muscle: Muscle, equipment: Equipment[]) {
  return filterExercises({ equipment, muscles: [muscle] })
}

